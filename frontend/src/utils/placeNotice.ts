/**
 * 신고 화면 '마지막 목격 장소' 검색 결과가 한 지점이 아닐 때 띄우는 안내.
 *
 * 서버(/geo/search)는 좌표가 무엇을 가리키는지 `granularity` 로 알려 준다 —
 * point(건물·역) | road(도로) | area(동·구). 도로·지역이면 좌표는 그 대표점이라
 * 실제 목격 지점과 멀 수 있다. 10/27 운영: "경기 고양시 일산서구 킨텍스로 217-60"
 * 검색이 도로 중심을 줘 실제 위치에서 약 2.5km 떨어졌다. 그 좌표가 그대로 예측의
 * 출발점(LKP)이 되므로 보호자가 지도를 보고 확인하게 한다.
 *
 * 신고 화면의 지도는 핀을 옮길 수 없다. 그래서 "다시 검색"으로 고치는 길을 함께 적는다.
 * 모르는 값(옛 서버라 필드가 없거나 새 값)이면 아무것도 띄우지 않는다.
 */
const NOTICE: Record<string, string> = {
  road: '도로 단위로만 찾았습니다. 지도의 위치가 맞는지 확인해 주세요. 다르면 건물이나 역 이름으로 다시 검색해 주세요.',
  area: '동네 단위로만 찾았습니다. 지도의 위치가 맞는지 확인해 주세요. 다르면 건물이나 역 이름으로 다시 검색해 주세요.',
};

export function placeNotice(granularity?: string | null): string | null {
  return (granularity && NOTICE[granularity]) || null;
}
